-- ============================================================
-- 6. LAB_CRAWLED_RECORD
-- ============================================================

CREATE TABLE LAB_CRAWLED_RECORD (
                                    ID NUMBER(19)
                                        GENERATED BY DEFAULT AS IDENTITY
                                        CONSTRAINT PK_LAB_CRAWLED_RECORD
                                            PRIMARY KEY,

                                    CHANNEL_ID NUMBER(19)
                                        NOT NULL,

                                    TITLE VARCHAR2(500),

                                    CONTENT CLOB,

                                    PUBLISHED_AT TIMESTAMP,

                                    CRAWLED_AT TIMESTAMP
                                        DEFAULT SYSTIMESTAMP
                                        NOT NULL,

                                    PROCESSING_STATUS VARCHAR2(20)
                                        NOT NULL,

                                    ERROR_MESSAGE VARCHAR2(1000),

                                    CREATED_AT TIMESTAMP
                                        DEFAULT SYSTIMESTAMP
                                        NOT NULL,

                                    CONSTRAINT FK_LAB_CRAWLED_RECORD_CHANNEL
                                        FOREIGN KEY (CHANNEL_ID)
                                            REFERENCES LAB_CHANNEL (ID)
);


