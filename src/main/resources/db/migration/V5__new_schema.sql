-- ============================================================
-- 1. LAB_AUTH_USER
-- ============================================================
-- Authentication / authorization information
-- ============================================================

CREATE TABLE LAB_AUTH_USER (
                               ID VARCHAR2(25)
                                   CONSTRAINT PK_LAB_AUTH_USER
                                       PRIMARY KEY,

                               USERNAME VARCHAR2(100)
                                   CONSTRAINT UK_LAB_AUTH_USER_USERNAME
                                       UNIQUE
                                   NOT NULL,

                               PASSWORD_HASH VARCHAR2(255)
                                   NOT NULL,

                               ROLE VARCHAR2(20)
                                   NOT NULL,

                               STATUS VARCHAR2(20)
                                   NOT NULL,

                               CREATED_AT TIMESTAMP
                                   DEFAULT SYSTIMESTAMP
                                   NOT NULL,

                               UPDATED_AT TIMESTAMP
                                   DEFAULT SYSTIMESTAMP
                                   NOT NULL
);


-- ============================================================
-- 2. LAB_USER_INFO
-- ============================================================
-- User profile / personal information
-- ============================================================

CREATE TABLE LAB_USER_INFO (
                               USER_ID VARCHAR2(25)
                                   CONSTRAINT PK_LAB_USER_INFO
                                       PRIMARY KEY,

                               FULL_NAME VARCHAR2(255),

                               EMAIL VARCHAR2(255)
                                   CONSTRAINT UK_LAB_USER_INFO_EMAIL
                                       UNIQUE,

                               PHONE_NUMBER VARCHAR2(30),

                               AVATAR_URL VARCHAR2(1000),

                               DATE_OF_BIRTH DATE,

                               CREATED_AT TIMESTAMP
                                   DEFAULT SYSTIMESTAMP
                                   NOT NULL,

                               UPDATED_AT TIMESTAMP
                                   DEFAULT SYSTIMESTAMP
                                   NOT NULL,

                               CONSTRAINT FK_LAB_USER_INFO_AUTH_USER
                                   FOREIGN KEY (USER_ID)
                                       REFERENCES LAB_AUTH_USER (ID)
);


