-- ============================================================
-- 4. LAB_CHANNEL
-- ============================================================

CREATE TABLE LAB_CHANNEL (
                             ID NUMBER(19)
                                 GENERATED BY DEFAULT AS IDENTITY
                                 CONSTRAINT PK_LAB_CHANNEL
                                     PRIMARY KEY,

                             DOMAIN_ID NUMBER(19)
                                 NOT NULL,

                             NAME VARCHAR2(255)
                                 NOT NULL,

                             PLATFORM_TYPE VARCHAR2(50)
                                 NOT NULL,

                             STATUS VARCHAR2(20)
                                 NOT NULL,

                             SOURCE_URL VARCHAR2(1000),

                             CONFIG CLOB,

                             CREATED_AT TIMESTAMP
                                 DEFAULT SYSTIMESTAMP
                                 NOT NULL,

                             CREATED_BY VARCHAR2(25)
                                 NOT NULL,

                             UPDATED_AT TIMESTAMP,

                             UPDATED_BY VARCHAR2(25),

                             CONSTRAINT CK_LAB_CHANNEL_STATUS
                                 CHECK (STATUS IN ('DRAFT', 'RUNNING', 'STOPPED'))
);


-- ============================================================
-- 5. LAB_CRAWLED_RECORD
-- ============================================================

CREATE TABLE LAB_CRAWLED_RECORD (
                                    ID NUMBER(19)
                                        GENERATED BY DEFAULT AS IDENTITY
                                        CONSTRAINT PK_LAB_CRAWLED_RECORD
                                            PRIMARY KEY,

                                    CHANNEL_ID NUMBER(19)
                                        NOT NULL,

                                    TITLE VARCHAR2(500),

                                    CONTENT CLOB,

                                    PUBLISHED_AT TIMESTAMP,

                                    CRAWLED_AT TIMESTAMP
                                        DEFAULT SYSTIMESTAMP
                                        NOT NULL,

                                    PROCESSING_STATUS VARCHAR2(20)
                                        NOT NULL,

                                    ERROR_MESSAGE VARCHAR2(1000),

                                    CREATED_AT TIMESTAMP
                                        DEFAULT SYSTIMESTAMP
                                        NOT NULL,

                                    CONSTRAINT CK_LAB_CRAWLED_RECORD_STATUS
                                        CHECK (
                                            PROCESSING_STATUS IN (
                                                                  'NEW',
                                                                  'PROCESSED',
                                                                  'ERROR'
                                                )
                                            )
);


