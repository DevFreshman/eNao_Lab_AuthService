-- ============================================================
-- 1. LAB_USER
-- ============================================================

CREATE TABLE LAB_USER (
                          ID VARCHAR2(25)
                              CONSTRAINT PK_LAB_USER
                                  PRIMARY KEY,

                          USERNAME VARCHAR2(100)
                              CONSTRAINT UK_LAB_USER_USERNAME
                                  UNIQUE
                              NOT NULL,

                          EMAIL VARCHAR2(255)
                              CONSTRAINT UK_LAB_USER_EMAIL
                                  UNIQUE
                              NOT NULL,

                          PASSWORD_HASH VARCHAR2(255)
                              NOT NULL,

                          FULL_NAME VARCHAR2(255),

                          ROLE VARCHAR2(20)
                              NOT NULL,

                          STATUS VARCHAR2(20)
                              NOT NULL,

                          CREATED_AT TIMESTAMP
                              DEFAULT SYSTIMESTAMP
                              NOT NULL,

                          UPDATED_AT TIMESTAMP
                              DEFAULT SYSTIMESTAMP
                              NOT NULL,

                          CONSTRAINT CK_LAB_USER_ROLE
                              CHECK (ROLE IN ('USER', 'ADMIN')),

                          CONSTRAINT CK_LAB_USER_STATUS
                              CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);


-- ============================================================
-- 2. LAB_DOMAIN
-- ============================================================

CREATE TABLE LAB_DOMAIN (
                            ID NUMBER(19)
                                GENERATED BY DEFAULT AS IDENTITY
                                CONSTRAINT PK_LAB_DOMAIN
                                    PRIMARY KEY,

                            CODE VARCHAR2(50)
                                CONSTRAINT UK_LAB_DOMAIN_CODE
                                    UNIQUE
                                NOT NULL,

                            NAME VARCHAR2(255)
                                NOT NULL,

                            STATUS VARCHAR2(20)
                                NOT NULL,

                            CREATED_AT TIMESTAMP
                                DEFAULT SYSTIMESTAMP
                                NOT NULL,

                            CREATED_BY VARCHAR2(25)
                                NOT NULL,

                            UPDATED_AT TIMESTAMP,

                            UPDATED_BY VARCHAR2(25),

                            CONSTRAINT CK_LAB_DOMAIN_STATUS
                                CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);


